class TestCatalog(Base):
    def test_roles_have_name_level_model_description_rules(self):
        for kind, roles in CATALOG.items():
            if kind == "other":
                continue
            with self.subTest(kind=kind):
                proj = os.path.join(self.tmp, "p_" + kind)
                os.makedirs(proj)
                data = {"name": "demo", "description": "a demo tool", "kind": kind,
                        "test_command": "make test", "production": False}
                path = os.path.join(self.tmp, "a_%s.json" % kind)
                with open(path, "w") as fh:
                    json.dump(data, fh)
                r = run(["--project", proj, "--answers", path], cwd=self.tmp)
                self.assertEqual(r.returncode, 0, r.stderr)
                for role, level in roles.items():
                    text = read(agent_path(proj, role))
                    fm = frontmatter(text)
                    self.assertEqual(fm["name"], role)
                    self.assertIn(level, fm["description"])
                    self.assertIn(MODEL[level], fm["description"])
                    self.assertEqual(fm["model"], MODEL[level])
                    rules = text.split("Rules:\n", 1)[1]
                    bullets = []
                    for line in rules.splitlines():
                        if line.startswith("- "):
                            bullets.append(line)
                        else:
                            break
                    self.assertTrue(2 <= len(bullets) <= 4, (role, bullets))

    def test_level_to_model_mapping_for_custom_roles(self):
        custom = [{"name": "r-%s" % lv, "level": lv, "description": "x", "knows": []}
                  for lv in MODEL]
        r = self.staff(self.base_answers(roles=[], custom_roles=custom))
        self.assertEqual(r.returncode, 0, r.stderr)
        for lv, model in MODEL.items():
            fm = frontmatter(read(agent_path(self.project, "r-" + lv)))
            self.assertEqual(fm["model"], model)


