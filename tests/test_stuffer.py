def load_script():
    """Import the script by path. Every test uses this one loader."""
    loader = SourceFileLoader("claude_stuffer", SCRIPT)
    spec = importlib.util.spec_from_loader("claude_stuffer", loader)
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


def run(args, cwd=None, home=None, input=None):
    """Run the script as a subprocess. HOME and CLAUDE_STUFFER_HOME never point at the real ~."""
    if not os.path.isfile(SCRIPT):
        raise FileNotFoundError("script under test is missing: " + SCRIPT)
    env = dict(os.environ)
    fake = home
    cleanup = None
    if fake is None:
        cleanup = tempfile.TemporaryDirectory()
        fake = cleanup.name
    env["HOME"] = fake
    env["CLAUDE_STUFFER_HOME"] = fake
    try:
        return subprocess.run([sys.executable, SCRIPT] + list(args), cwd=cwd, env=env,
                              input=input, capture_output=True, text=True, timeout=60)
    finally:
        if cleanup:
            cleanup.cleanup()


def make_files(base, files):
    for rel, content in files.items():
        path = os.path.join(base, rel)
        if rel.endswith("/"):
            os.makedirs(path, exist_ok=True)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as fh:
            fh.write(content)


def read(path):
    with open(path) as fh:
        return fh.read()


def agent_path(project, name):
    return os.path.join(project, ".claude", "agents", name + ".md")


def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    assert m, "no frontmatter in:\n" + text
    out = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        out[k.strip()] = v.strip()
    return out


def line_with(text, prefix):
    for line in text.splitlines():
        if line.startswith(prefix):
            return line
    return None


class Base(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.tmp = self._tmp.name
        self.project = os.path.join(self.tmp, "proj")
        os.makedirs(self.project)
        self.home = os.path.join(self.tmp, "home")
        os.makedirs(self.home)

    def answers(self, data):
        path = os.path.join(self.tmp, "answers.json")
        with open(path, "w") as fh:
            json.dump(data, fh)
        return path

    def staff(self, data, extra=()):
        return run(["--project", self.project, "--answers", self.answers(data)] + list(extra),
                   cwd=self.tmp)

    def base_answers(self, **over):
        data = {"name": "demo", "description": "a demo tool", "kind": "cli",
                "roles": ["cli-developer"]}
        data.update(over)
        return data


