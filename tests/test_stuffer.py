class TestRerun(Base):
    def setUp(self):
        super().setUp()
        make_files(self.project, {"go.mod": "module x\n"})
        self.data = self.base_answers(test_command="go test ./...")

    def test_rerun_keeps_agent_files_and_one_team_block(self):
        self.staff(self.data)
        path = agent_path(self.project, "cli-developer")
        before = read(path)
        r = self.staff(self.data)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(read(path), before)
        self.assertIn("kept", r.stdout)
        text = read(os.path.join(self.project, "CLAUDE.md"))
        self.assertEqual(text.count(TEAM_START), 1)
        self.assertEqual(text.count(TEAM_END), 1)

    def test_force_rewrites_generated_file(self):
        self.staff(self.data)
        path = agent_path(self.project, "cli-developer")
        with open(path, "a") as fh:
            fh.write("\nLOCAL EDIT\n")
        self.staff(self.data)
        self.assertIn("LOCAL EDIT", read(path))
        r = self.staff(self.data, ["--force"])
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertNotIn("LOCAL EDIT", read(path))

    def test_hand_written_agent_never_overwritten_even_with_force(self):
        path = agent_path(self.project, "cli-developer")
        os.makedirs(os.path.dirname(path))
        with open(path, "w") as fh:
            fh.write("---\nname: cli-developer\n---\nmine\n")
        r = self.staff(self.data, ["--force"])
        self.assertEqual(read(path), "---\nname: cli-developer\n---\nmine\n")
        self.assertIn("not ours", r.stdout)


